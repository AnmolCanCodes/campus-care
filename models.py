from datetime import datetime

from sqlalchemy import Column, DateTime, ForeignKey, Integer, String, Text
from sqlalchemy.orm import relationship

from database import Base


class Student(Base):
    __tablename__ = "students"

    id = Column(Integer, primary_key=True, index=True)
    name = Column(String(100), nullable=False)
    roll_number = Column(String(30), unique=True, nullable=False, index=True)
    course = Column(String(60), nullable=False)
    semester = Column(Integer, nullable=False)
    email = Column(String(120), nullable=False)

    complaints = relationship("Complaint", back_populates="student")


class Complaint(Base):
    __tablename__ = "complaints"

    id = Column(Integer, primary_key=True, index=True)
    student_id = Column(Integer, ForeignKey("students.id"), nullable=False)
    category = Column(String(40), nullable=False)
    subject = Column(String(200), nullable=False)      # written by the student
    description = Column(Text, nullable=False)         # written by the student
    ai_subject = Column(String(200), nullable=False)   # generated by the AI
    priority = Column(String(10), nullable=False)      # Low / Medium / High
    ai_email = Column(Text, nullable=False)            # full email, signature included
    created_at = Column(DateTime, default=datetime.now, nullable=False)

    student = relationship("Student", back_populates="complaints")


class Rant(Base):
    """Anonymous on purpose: no student information is stored here."""

    __tablename__ = "rants"

    id = Column(Integer, primary_key=True, index=True)
    content = Column(Text, nullable=False)
    created_at = Column(DateTime, default=datetime.now, nullable=False)